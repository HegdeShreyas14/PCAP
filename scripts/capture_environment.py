"""
capture_environment.py — snapshot the machine and software environment for
the paper's reproducibility appendix, and regenerate ENVIRONMENT.md.

Writes
    results/environment/system.json          hardware, OS, BLAS, power, GPU
    results/environment/requirements-lock.txt full `pip freeze` of the venv
    ENVIRONMENT.md                            human-readable summary, plus a
                                              provenance table built from every
                                              results/*_env.json

Run on the machine that produced the datasets, ideally in the same session:

    .venv/bin/python scripts/capture_environment.py
"""

import glob
import json
import os
import subprocess
import sys
from datetime import datetime

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "src"))
from provenance import run_metadata  # noqa: E402

OUT = os.path.join(ROOT, "results", "environment")


def torch_info():
    try:
        import torch
        info = {"torch": torch.__version__, "torch_cuda": torch.version.cuda,
                "cudnn": torch.backends.cudnn.version(),
                "cuda_available": torch.cuda.is_available()}
        if torch.cuda.is_available():
            prop = torch.cuda.get_device_properties(0)
            info.update(gpu=prop.name,
                        compute_capability=f"{prop.major}.{prop.minor}",
                        vram_visible_to_cuda_mib=prop.total_memory // 2**20,
                        sm_count=prop.multi_processor_count)
        return info
    except ImportError:
        return {"torch": None}


def machine_states():
    """(timestamp, filename) for each results/runlogs/machine_state*.txt."""
    out = []
    for path in glob.glob(os.path.join(ROOT, "results", "runlogs", "machine_state*.txt")):
        first = (open(path).readline().split() or ["", ""])
        if first[0] == "recorded":
            out.append((first[1][:19], os.path.basename(path)))
    return sorted(out)


def dataset_rows():
    states = machine_states()
    rows = []
    for path in sorted(glob.glob(os.path.join(ROOT, "results", "*_env.json"))):
        d = json.load(open(path))
        p = d.get("provenance", d)              # sweep.py nests it
        csv = os.path.basename(path).replace("_env.json", ".csv")
        threads = (p.get("blas_threads") or {}).get("OMP_NUM_THREADS") \
            if isinstance(p.get("blas_threads"), dict) else d.get("blas_threads")
        rows.append({
            "dataset": csv,
            "date": (p.get("timestamp") or "")[:16].replace("T", " "),
            "commit": (p.get("git_commit") or "?")[:7],
            "src_dirty": p.get("src_dirty"),
            "blas_threads": threads,
            "kernel": (p.get("platform") or "").split("-with")[0]
                      .replace("Linux-", "").replace("-x86_64", ""),
            # the machine-state record taken most recently before this run
            "state": next((f for ts, f in reversed(states)
                           if ts <= (p.get("timestamp") or "")[:19]), "not recorded"),
        })
    return rows


def main():
    os.makedirs(OUT, exist_ok=True)
    meta = run_metadata()
    s = meta["system"]
    t = torch_info()
    snapshot = {"captured": datetime.now().isoformat(timespec="seconds"),
                "git_commit": meta["git_commit"], "src_dirty": meta["src_dirty"],
                "python": meta["python"], "system": s, "torch": t,
                "packages": {k: meta[k] for k in ("numpy", "scipy", "networkx", "gglasso")}}
    with open(os.path.join(OUT, "system.json"), "w") as f:
        json.dump(snapshot, f, indent=2, default=str)

    # `python -m pip`, not .venv/bin/pip: the venv was moved after creation and
    # its pip launcher's shebang points at the old path.
    freeze = subprocess.run([sys.executable, "-m", "pip", "freeze"],
                            capture_output=True, text=True, check=True).stdout
    with open(os.path.join(OUT, "requirements-lock.txt"), "w") as f:
        f.write(f"# pip freeze of the venv that produced results/, captured "
                f"{snapshot['captured']}\n# Python {meta['python']}. torch wheel "
                f"index: https://download.pytorch.org/whl/cu130\n")
        f.write(freeze)

    rows = dataset_rows()
    smi = (s.get("nvidia_smi") or ",,,").split(", ")
    md = f"""# Environment

Generated by `scripts/capture_environment.py` on {snapshot['captured'][:10]}
(commit `{(meta['git_commit'] or '?')[:7]}`). Do not edit by hand; re-run the
script. Machine-readable versions: `results/environment/system.json`,
`results/environment/requirements-lock.txt` (all {len(freeze.splitlines())} packages).

## Hardware

| | |
|---|---|
| Machine | {s.get('machine_vendor')} {s.get('machine_product')} (BIOS {s.get('bios_version')}) |
| CPU | {s.get('cpu_model')} — {s.get('cpu_physical_cores')} physical / {s.get('cpu_logical_cores')} logical cores, SMT {'on' if s.get('smt_active') == '1' else 'off'} |
| RAM | {s.get('ram_gib')} GiB |
| GPU | {t.get('gpu', smi[0])}, compute capability {t.get('compute_capability', smi[2] if len(smi) > 2 else '?')}, {smi[3] if len(smi) > 3 else '?'} nominal / {t.get('vram_visible_to_cuda_mib', '?')} MiB visible to CUDA |
| GPU driver | {smi[1] if len(smi) > 1 else '?'} |

## Software

| | |
|---|---|
| OS | {s.get('os')}, kernel {s.get('kernel')}, {s.get('libc')} |
| Python | {meta['python']} (venv) |
| BLAS / LAPACK | {s.get('blas_library')} (bundled with numpy) |
| numpy / scipy / networkx | {meta['numpy']} / {meta['scipy']} / {meta['networkx']} |
| gglasso | {meta['gglasso']} |
| torch | {t.get('torch')} (CUDA {t.get('torch_cuda')}, cuDNN {t.get('cudnn')}) |

## Run conditions for timed experiments

| | |
|---|---|
| CPU frequency driver / governor / EPP | {s.get('cpufreq_driver')} / {s.get('cpufreq_governor')} / {s.get('cpufreq_epp')} |
| Power profile | {s.get('power_profile')} (mains power) |
| BLAS threads | pinned per run before numpy import; 1 or 8 (never more than physical cores) — see each dataset below |
| Competing load | none: browsers closed, unrelated Docker container stopped. Recorded per run in `results/runlogs/machine_state*.txt` |
| Repetitions | 2 warm-up runs, then 9 timed (RQ1 sweeps, batched benchmarks) or 5 timed (GPU crossover / VRAM anchors); median reported with full trial vectors stored |

Two earlier datasets were invalidated by exactly these conditions: BLAS
behaviour made the sampled data thread-dependent (bug 8), and a throttled CPU
baseline inflated GPU/CPU ratios ~30% (bug 9). See `notes/ProgressLog.md`.

## Dataset provenance

Every dataset has an `_env.json` with the commit, a dirty-tree flag, md5 of
every source file, package versions, BLAS threads and the full command line.

| dataset | produced | commit | src clean | BLAS threads | kernel | machine state |
|---|---|---|---|---|---|---|
""" + "\n".join(
        f"| `{r['dataset']}` | {r['date']} | `{r['commit']}` | "
        f"{'yes' if r['src_dirty'] is False else 'NO' if r['src_dirty'] else '?'} | "
        f"{r['blas_threads']} | {r['kernel']} | `runlogs/{r['state']}` |" for r in rows) + """

## Reproducing

```bash
python3.12 -m venv .venv && source .venv/bin/activate
pip install -r results/environment/requirements-lock.txt \\
    --extra-index-url https://download.pytorch.org/whl/cu130
python tests/test_sampling_determinism.py   # must pass before any run
scripts/rerun_bug8.sh                       # RQ1 sweeps + percolation (~2 h)
scripts/rerun_rq2_rq3.sh                    # batched CPU/GPU, crossover, VRAM (~20 min; needs CUDA GPU)
python src/make_graph.py                    # all figures from results/
```

Timings are machine-specific; the structural results (detected blocks, F1,
F_max, objective values) are deterministic given the seed and reproduce
across BLAS thread counts to ~1e-12.
"""
    with open(os.path.join(ROOT, "ENVIRONMENT.md"), "w") as f:
        f.write(md)
    print(f"wrote {OUT}/system.json, requirements-lock.txt "
          f"({len(freeze.splitlines())} packages) and ENVIRONMENT.md "
          f"({len(rows)} datasets)")
    if meta["src_dirty"]:
        print("!! src/ has uncommitted changes: commit before capturing for the paper.")


if __name__ == "__main__":
    main()
